package com.indivaragroup.operator.compare.operation;

public class CompareOperation {
    public void compareOperationFunction(){

        int a = 5;
        int b = 11;

        System.out.println(a>b);        //false
        System.out.println(a<b);        //true
        System.out.println(a>=b);       //false
        System.out.println(a<=b);       //true
        System.out.println(a==b);       //false
        System.out.println(a!=b);       //true
    }
}
